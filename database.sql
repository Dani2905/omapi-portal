-- Schéma PostgreSQL du portail OMAPI.
-- Aucune donnée ni aucun secret n'est inclus dans ce fichier.
-- À exécuter uniquement dans la base OMAPI dédiée (jamais dans la base du site Cabinet).

BEGIN;

CREATE TABLE IF NOT EXISTS app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'Éditeur' CHECK (role IN ('Admin', 'Éditeur')),
  status TEXT NOT NULL DEFAULT 'Actif' CHECK (status IN ('Actif', 'Inactif')),
  -- Hash scrypt généré côté serveur ; jamais un mot de passe en clair.
  password_hash TEXT NOT NULL,
  password_changed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS app_users_email_lower_uq ON app_users (LOWER(email));

CREATE TABLE IF NOT EXISTS admin_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS admin_sessions_user_expiry_idx ON admin_sessions (user_id, expires_at);

CREATE TABLE IF NOT EXISTS news (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  display_date TEXT NOT NULL,
  category TEXT NOT NULL,
  image_url TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  content TEXT,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS news_featured_idx ON news (featured);

CREATE TABLE IF NOT EXISTS home_slides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  image_url TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL DEFAULT '',
  subtitle TEXT NOT NULL DEFAULT '',
  cta_text TEXT NOT NULL DEFAULT '',
  cta_link TEXT NOT NULL DEFAULT '',
  news_id BIGINT REFERENCES news(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS home_resources (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  omapi_hour_title TEXT NOT NULL DEFAULT 'L''Heure OMAPI & Ateliers pratiques',
  omapi_hour_description TEXT NOT NULL DEFAULT 'Découvrez les rencontres, échanges et ateliers consacrés à la propriété industrielle à Madagascar.',
  omapi_hour_thumbnail TEXT NOT NULL DEFAULT '/resources/omapi-hour.jpg',
  omapi_hour_url TEXT NOT NULL DEFAULT '/events',
  video_title TEXT NOT NULL DEFAULT 'Guides pratiques de propriété industrielle',
  video_description TEXT NOT NULL DEFAULT 'Consultez les ressources disponibles pour mieux comprendre les démarches et le suivi de vos titres.',
  video_thumbnail TEXT NOT NULL DEFAULT '/resources/omapi-video.jpg',
  video_duration TEXT NOT NULL DEFAULT '',
  video_url TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO home_resources (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS site_config (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  news_section_bg_image TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO site_config (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS forms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL CHECK (category IN ('Marques', 'Brevets', 'Dessins', 'Autres')),
  file_url TEXT,
  file_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS guides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  icon_name TEXT NOT NULL,
  points TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  color_theme TEXT NOT NULL CHECK (color_theme IN ('blue', 'amber', 'purple', 'emerald', 'orange', 'gray')),
  file_url TEXT,
  file_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS legislation_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('Fondamental', 'Application', 'Autre')),
  document_type TEXT NOT NULL CHECK (document_type IN ('Loi', 'Ordonnance', 'Décret', 'Arrêté', 'Autre')),
  display_date TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  file_url TEXT NOT NULL,
  file_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS gopi_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  publication_period TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT,
  file_url TEXT,
  file_name TEXT,
  cover_image TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS gopi_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gopi_id BIGINT REFERENCES gopi_items(id) ON DELETE SET NULL,
  gopi_title TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  customer_email TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  order_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  amount_mga NUMERIC(12, 2),
  status TEXT NOT NULL DEFAULT 'En attente' CHECK (status IN ('En attente', 'Paiement confirmé', 'Envoyé', 'Annulé')),
  transaction_ref TEXT,
  payment_method TEXT,
  payment_confirmed_at TIMESTAMPTZ,
  sent_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS gopi_orders_status_date_idx ON gopi_orders (status, order_date DESC);
CREATE INDEX IF NOT EXISTS gopi_orders_email_lower_idx ON gopi_orders (LOWER(customer_email));

CREATE TABLE IF NOT EXISTS formations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('Base', 'Avancee')),
  event_date DATE,
  event_time TEXT,
  location TEXT,
  description TEXT,
  conditions TEXT,
  color_theme TEXT CHECK (color_theme IS NULL OR color_theme IN ('blue', 'emerald', 'amber', 'rose', 'indigo', 'purple', 'cyan')),
  file_url TEXT,
  file_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS formation_registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  formation_id BIGINT NOT NULL REFERENCES formations(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  organization TEXT,
  message TEXT,
  registration_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS formation_registrations_email_uq ON formation_registrations (formation_id, LOWER(email));

CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  event_date DATE NOT NULL,
  event_time TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'À venir' CHECK (status IN ('À venir', 'En cours', 'Terminé', 'Annulé')),
  places TEXT,
  file_url TEXT,
  file_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS events_date_status_idx ON events (event_date, status);

CREATE TABLE IF NOT EXISTS event_registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  organization TEXT,
  registration_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS event_registrations_email_uq ON event_registrations (event_id, LOWER(email));

CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  department TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  employment_type TEXT NOT NULL CHECK (employment_type IN ('CDI', 'CDD', 'Stage', 'Consultant')),
  experience TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Ouvert' CHECK (status IN ('Ouvert', 'Fermé')),
  publish_date DATE NOT NULL DEFAULT CURRENT_DATE,
  deadline DATE,
  file_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS job_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT REFERENCES jobs(id) ON DELETE SET NULL,
  job_title TEXT,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  message TEXT,
  cv_url TEXT NOT NULL,
  cv_file_name TEXT,
  cover_letter_url TEXT,
  cover_letter_file_name TEXT,
  application_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status TEXT NOT NULL DEFAULT 'Nouvelle' CHECK (status IN ('Nouvelle', 'En cours', 'Rejetée', 'Acceptée')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS job_applications_status_date_idx ON job_applications (status, application_date DESC);
CREATE INDEX IF NOT EXISTS job_applications_email_lower_idx ON job_applications (LOWER(email));

CREATE TABLE IF NOT EXISTS activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
  user_name TEXT NOT NULL DEFAULT 'Visiteur',
  entity_key TEXT,
  entity_id TEXT,
  action TEXT NOT NULL,
  details TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS activity_logs_occurred_at_idx ON activity_logs (occurred_at DESC);

COMMIT;
