import assert from 'node:assert/strict';
import { DEFAULT_USERS } from '../data/mocks/users';
import type { User } from '../types';
import {
  createPasswordCredential,
  generateTemporaryPassword,
  hasPasswordCredential,
  validateAccountDeletion,
  validateAccountModification,
  normalizeEmail,
  normalizeName,
  validateNewPassword,
  validatePasswordSelection,
  validateProfilePasswordChange,
  validateUserDraft,
  verifyPasswordCredential,
  SUPER_ADMIN_EMAILS,
} from '../utils/userAccounts';

async function main() {
  console.log('Test 1 — création valide + normalisation');
  const draft: Partial<User> = {
    name: '  Utilisateur   Test  ',
    email: '  nouveau.compte@example.invalid ',
    role: 'Éditeur',
    status: 'Actif',
  };
  assert.equal(normalizeName(draft.name), 'Utilisateur Test');
  assert.equal(normalizeEmail(draft.email), 'nouveau.compte@example.invalid');
  assert.deepEqual(validateUserDraft(draft, DEFAULT_USERS), {});

  console.log("Test 2 — doublon d'e-mail refusé (casse/espaces ignorés)");
  const existingDuplicate: User = {
    id: 700,
    name: 'Compte existant',
    email: 'duplicate@example.invalid',
    role: 'Éditeur',
    status: 'Actif',
  };
  const duplicate = validateUserDraft(
    { name: 'Copie', email: ' DUPLICATE@example.invalid ' },
    [...DEFAULT_USERS, existingDuplicate],
  );
  assert.match(duplicate.email ?? '', /existe déjà/);

  console.log("Test 3 — édition du même utilisateur sans changer son e-mail");
  assert.deepEqual(
    validateUserDraft(
      { ...DEFAULT_USERS[1], name: 'Compte modifié' },
      DEFAULT_USERS,
      DEFAULT_USERS[1].id,
    ),
    {},
  );

  console.log('Test 4 — adresse réservée refusée pour un nouveau compte');
  const reserved = validateUserDraft(
    { name: 'Faux Admin', email: SUPER_ADMIN_EMAILS[0] },
    DEFAULT_USERS,
  );
  assert.match(reserved.email ?? '', /réservée/);

  console.log('Test 5 — compte administrateur principal modifiable par son titulaire');
  assert.deepEqual(
    validateUserDraft(
      { ...DEFAULT_USERS[0], name: 'Administrateur principal modifié' },
      DEFAULT_USERS,
      DEFAULT_USERS[0].id,
    ),
    {},
  );

  console.log('Test 6 — champs invalides refusés');
  assert.match(
    validateUserDraft({ name: ' ', email: 'pas-un-email' }, DEFAULT_USERS).name ?? '',
    /obligatoire/,
  );
  assert.match(
    validateUserDraft({ name: 'Test', email: 'pas-un-email' }, DEFAULT_USERS).email ?? '',
    /valide/,
  );

  console.log('Test 7 — mot de passe manuel : vide/court refusés, valeur sûre acceptée');
  assert.match(validatePasswordSelection('manual', '') ?? '', /Saisissez/);
  assert.match(validatePasswordSelection('manual', 'court') ?? '', /8 caractères/);
  assert.equal(validatePasswordSelection('manual', generateTemporaryPassword()), undefined);
  assert.equal(validatePasswordSelection('none', ''), undefined);

  console.log('Test 8 — mot de passe temporaire réellement aléatoire');
  const generated = Array.from({ length: 20 }, () => generateTemporaryPassword());
  assert.ok(generated.every((password) => password.length === 14));
  assert.ok(new Set(generated).size > 1, 'les valeurs générées ne doivent pas être constantes');
  assert.ok(generated.every((password) => !password.includes('AutoGenerated')));
  assert.ok(generated.every((password) =>
    /[a-z]/.test(password) && /[A-Z]/.test(password) && /\d/.test(password) && /[^A-Za-z\d]/.test(password),
  ));

  console.log('Test 9 — nouvel utilisateur : empreinte + reconnexion');
  const chosenPassword = generateTemporaryPassword();
  const credentialA = await createPasswordCredential(chosenPassword);
  const credentialB = await createPasswordCredential(chosenPassword);
  const createdUser: User = {
    id: Date.now(),
    name: normalizeName(draft.name),
    email: normalizeEmail(draft.email),
    role: 'Éditeur',
    status: 'Actif',
    ...credentialA,
  };

  assert.equal(hasPasswordCredential(createdUser), true);
  assert.notEqual(credentialA.passwordSalt, credentialB.passwordSalt);
  assert.notEqual(credentialA.passwordHash, credentialB.passwordHash);
  assert.equal(JSON.stringify(createdUser).includes(chosenPassword), false, 'aucune valeur en clair');
  assert.equal(await verifyPasswordCredential(chosenPassword, createdUser), true);
  assert.equal(await verifyPasswordCredential('wrong', createdUser), false);
  assert.equal(normalizeEmail(` ${draft.email} `), createdUser.email);

  console.log('Test 10 — changement de mot de passe du profil : validations');
  const currentPassword = generateTemporaryPassword();
  const nextPassword = generateTemporaryPassword();
  assert.equal(validateProfilePasswordChange({
    currentPassword: '', newPassword: '', confirmPassword: '', hasCurrentCredential: true,
  }), undefined, 'aucun champ rempli = aucun changement demandé');
  assert.match(validateProfilePasswordChange({
    currentPassword: '', newPassword: nextPassword, confirmPassword: nextPassword, hasCurrentCredential: true,
  }) ?? '', /mot de passe actuel/);
  assert.match(validateProfilePasswordChange({
    currentPassword, newPassword: nextPassword, confirmPassword: generateTemporaryPassword(), hasCurrentCredential: true,
  }) ?? '', /ne correspondent pas/);
  assert.match(validateProfilePasswordChange({
    currentPassword, newPassword: currentPassword, confirmPassword: currentPassword, hasCurrentCredential: true,
  }) ?? '', /différent/);
  assert.match(validateProfilePasswordChange({
    currentPassword, newPassword: '  ', confirmPassword: '  ', hasCurrentCredential: true,
  }) ?? '', /espace/);
  assert.equal(validateProfilePasswordChange({
    currentPassword: '', newPassword: nextPassword, confirmPassword: nextPassword, hasCurrentCredential: false,
  }), undefined, 'un compte hérité sans mot de passe peut en définir un premier');
  assert.match(validateNewPassword('court') ?? '', /8 caractères/);

  console.log("Test 11 — changement effectif : l'ancien mot de passe cesse de fonctionner");
  const oldPassword = generateTemporaryPassword();
  const replacementPassword = generateTemporaryPassword();
  const beforeChange: User = {
    id: 987654,
    name: 'Compte de test',
    email: 'compte.changement@example.invalid',
    role: 'Éditeur',
    status: 'Actif',
    ...(await createPasswordCredential(oldPassword)),
  };
  assert.equal(await verifyPasswordCredential(oldPassword, beforeChange), true);
  assert.equal(await verifyPasswordCredential('wrong', beforeChange), false);

  const afterChange: User = {
    ...beforeChange,
    ...(await createPasswordCredential(replacementPassword)),
  };
  assert.notEqual(afterChange.passwordSalt, beforeChange.passwordSalt);
  assert.notEqual(afterChange.passwordHash, beforeChange.passwordHash);
  assert.equal(await verifyPasswordCredential(oldPassword, afterChange), false);
  assert.equal(await verifyPasswordCredential(replacementPassword, afterChange), true);
  assert.equal(JSON.stringify(afterChange).includes(replacementPassword), false);

  console.log('Test 12 — modification de compte : protection du principal et du dernier Admin');
  const secondAdmin: User = {
    id: 88,
    name: 'Administrateur secondaire',
    email: 'second.admin@example.invalid',
    role: 'Admin',
    status: 'Actif',
  };
  const usersWithSecondAdmin = [...DEFAULT_USERS, secondAdmin];

  assert.equal(
    validateAccountModification(
      usersWithSecondAdmin,
      secondAdmin,
      { ...secondAdmin, name: 'Admin modifié', role: 'Admin', status: 'Actif' },
      DEFAULT_USERS[0].id,
    ),
    undefined,
    'un administrateur peut modifier les informations normales d’un autre compte',
  );
  assert.match(
    validateAccountModification(
      usersWithSecondAdmin,
      secondAdmin,
      { ...secondAdmin, role: 'Éditeur' },
      secondAdmin.id,
    ) ?? '',
    /propre rôle/,
  );
  assert.match(
    validateAccountModification(
      DEFAULT_USERS,
      DEFAULT_USERS[0],
      { ...DEFAULT_USERS[0], status: 'Inactif' },
      DEFAULT_USERS[0].id,
    ) ?? '',
    /principal doit rester Admin et actif/,
  );
  assert.match(
    validateAccountModification(
      DEFAULT_USERS,
      DEFAULT_USERS[0],
      { ...DEFAULT_USERS[0], email: 'nouvelle.adresse@example.invalid' },
      DEFAULT_USERS[0].id,
    ) ?? '',
    /e-mail du compte administrateur principal/,
  );
  assert.match(
    validateAccountModification(
      DEFAULT_USERS,
      DEFAULT_USERS[0],
      { ...DEFAULT_USERS[0], role: 'Éditeur' },
      DEFAULT_USERS[0].id,
    ) ?? '',
    /principal doit rester Admin et actif/,
  );

  console.log('Test 13 — suppression de compte : auto-suppression, principal, dernier Admin');
  assert.equal(validateAccountDeletion(usersWithSecondAdmin, DEFAULT_USERS[1], DEFAULT_USERS[0].id), undefined);
  assert.match(validateAccountDeletion(DEFAULT_USERS, DEFAULT_USERS[0], DEFAULT_USERS[0].id) ?? '', /principal/);
  assert.match(validateAccountDeletion(usersWithSecondAdmin, secondAdmin, secondAdmin.id) ?? '', /propre compte/);
  assert.match(validateAccountDeletion(usersWithSecondAdmin, DEFAULT_USERS[0], secondAdmin.id) ?? '', /administrateur principal/);
  assert.match(validateAccountDeletion([secondAdmin], secondAdmin, DEFAULT_USERS[0].id) ?? '', /dernier administrateur actif/);
  assert.match(validateAccountDeletion(usersWithSecondAdmin, undefined, DEFAULT_USERS[0].id) ?? '', /n'existe déjà plus/);

  console.log('\nTous les tests utilisateurs, modification et suppression PASSENT.');
}

main().catch((error) => {
  console.error('\nECHEC DES TESTS:', error);
  process.exit(1);
});
